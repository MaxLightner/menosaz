export function defaultMenuName(kind:string){
 return MENU_KINDS.find(k=>k.id===kind)?.menuName||'منوی رستوران';
}
export function menuKindLabel(kind:string){
 return MENU_KINDS.find(k=>k.id===kind)?.title||'منوی اختصاصی';
}
export function effectiveMenuName(name:string,kind:string){
 const clean=(name||'').trim();
 return !clean||clean==='منوی اصلی'||clean==='منو اصلی'?defaultMenuName(kind):clean;
}
export function menuIdentityLabel(name:string,kind:string,index:number,allNames:string[]){
 const base=effectiveMenuName(name,kind);
 // Multiple legacy records may share a name. Give each a distinct selector label.
 const duplicates=allNames.slice(0,index).filter(n=>n===base).length;
 return duplicates?`${base} · ${duplicates+1}`:base;
}
