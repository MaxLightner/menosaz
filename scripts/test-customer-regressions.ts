import {buildVariants,variantGroup,variantChoice} from '../src/lib/productVariants';
import {catalogImagePath,displayImagePath} from '../src/lib/imagePath';
import assert from 'node:assert/strict';
import {addCartItem} from '../src/lib/cart';
import {viewFromSearch} from '../src/lib/navigation';
import {customerOrderStatus} from '../src/lib/orderRules';
import {localProductImage} from '../src/services/menuPresentation';
import type {Product,OrderItemOption} from '../src/types';
const product:Product={id:'p',businessId:'b',categoryId:'food',name:'پیتزا',description:'',price:100,isAvailable:true,imageUrl:'/menu-assets/cappuccino.webp',prepTimeMinutes:10,updatedAt:''};
const option=(groupId:string,optionId:string,extraPrice:number):OrderItemOption=>({groupId,optionId,groupTitle:'اندازه',optionName:'بزرگ',extraPrice});
let checks=0;
let cart=addCartItem([],product,[],'بدون پیاز');
cart=addCartItem(cart,product,[],'با پیاز');
assert.equal(cart.length,2);assert.deepEqual(cart.map(i=>i.notes),['بدون پیاز','با پیاز']);checks++;
cart=addCartItem(cart,product,[],'بدون پیاز');assert.equal(cart[0].quantity,2);assert.equal(cart[0].itemTotal,200);checks++;
// Notes can be edited after addition: matching must use current data, not the old row ID.
cart=cart.map(i=>i===cart[0]?{...i,notes:'بدون نمک'}:i);
cart=addCartItem(cart,product,[],'بدون پیاز');assert.equal(cart.length,3);assert.equal(cart[2].quantity,1);checks++;
cart=addCartItem([],product,[option('g1','a',10)]);
cart=addCartItem(cart,product,[option('g2','b',50)]);
assert.equal(cart.length,2);assert.equal(cart.reduce((n,i)=>n+i.itemTotal,0),260);checks++;
const a=option('g1','a',10),b=option('g2','b',50);
cart=addCartItem([],product,[a,b]);cart=addCartItem(cart,product,[b,a]);assert.equal(cart.length,1);assert.equal(cart[0].quantity,2);assert.equal(cart[0].itemTotal,320);checks++;
cart=addCartItem([],product,[{...a,groupId:undefined,optionId:undefined,groupTitle:'نان'}]);cart=addCartItem(cart,product,[{...a,groupId:undefined,optionId:undefined,groupTitle:'نوشیدنی'}]);assert.equal(cart.length,2);checks++;
cart=addCartItem([],product);cart=addCartItem(cart,{...product,price:200});assert.equal(cart.length,2);assert.equal(cart.reduce((n,i)=>n+i.itemTotal,0),300);checks++;
assert.equal(viewFromSearch(''),'website');assert.equal(viewFromSearch('?view=how'),'how');assert.equal(viewFromSearch('?view=terms'),'terms');assert.equal(viewFromSearch('?q=table-token'),'customer');assert.equal(viewFromSearch('?view=unknown'),'website');checks++;
// Inaccurate bundled placeholder photos are replaced by item-matching lightweight tiles.
assert.equal(localProductImage(product),'/menu-tiles/food-15.webp');
assert.equal(localProductImage({...product,customImage:true,imageUrl:'https://example.com/photo.webp'}),'https://example.com/photo.webp');
assert.equal(localProductImage({...product,imageUrl:''}),'/menu-tiles/food-15.webp');checks++;
assert.equal(customerOrderStatus({status:'cancelled',deliveryStatus:'pending'}),'لغو شد');
assert.equal(customerOrderStatus({status:'delivered',deliveryStatus:'delivered'}),'تحویل داده شد');
assert.equal(customerOrderStatus({status:'pending_waiter',deliveryStatus:'pending'}),'در انتظار گارسون');
assert.equal(customerOrderStatus({status:'ready',deliveryStatus:'pending'}),'آماده تحویل به گارسون');
assert.equal(customerOrderStatus({status:'cooking',deliveryStatus:'pending'}),'در انتظار تأیید آشپزخانه');checks++;
assert.equal(displayImagePath('/menu-tiles/food-0.webp','/menosaz/'),'/menosaz/menu-tiles/food-0.webp');
assert.equal(displayImagePath('/menu-tiles/service.svg','/menosaz/'),'/menosaz/menu-tiles/service.svg');
assert.equal(displayImagePath('/menu-assets/cappuccino.webp','/menosaz/'),'/menosaz/menu-assets/cappuccino.webp');assert.equal(displayImagePath('/menosaz/media/food-0.webp','/menosaz/'),'/menosaz/media/food-0.webp');assert.equal(catalogImagePath('/menosaz/media/food-0.webp','/menosaz/'),'/media/food-0.webp');assert.equal(displayImagePath('https://example.com/photo.webp','/menosaz/'),'https://example.com/photo.webp');checks++;
console.log(`PASS: ${checks} customer cart/instructions/options/pricing/navigation/images/status regression scenarios`);

const sizes=buildVariants([{id:'one',name:'یک‌نفره',price:'100'},{id:'two',name:'دونفره',price:'200'}],100,'اندازه')!;
const sized={...product,optionGroups:[sizes]};
assert.equal(variantGroup(sized)?.id,sizes.id);
cart=addCartItem([],sized,[variantChoice(sizes,sizes.options[0])]);
cart=addCartItem(cart,sized,[variantChoice(sizes,sizes.options[1])]);
assert.equal(cart.length,2);assert.equal(cart.reduce((n,i)=>n+i.itemTotal,0),300);
assert.throws(()=>buildVariants([{id:'x',name:'بزرگ',price:'-1'}],100,'اندازه'));
assert.throws(()=>buildVariants([{id:'x',name:'',price:'100'}],100,'اندازه'));
assert.throws(()=>buildVariants([{id:'x',name:'تکراری',price:'100'},{id:'y',name:'تکراری',price:'100'}],100,'اندازه'));
assert.equal(buildVariants([],100,'اندازه'),undefined);
console.log('PASS: model editing, final prices, separate selections and invalid model rejection');
